def slugify(text):
    text = text.lower()
    text = re.sub(r'[^a-z0-9]+', '-', text).strip('-')
    return text

def build_answer_capsule(brand, kw_text, cap, persona, industry):
    """
    Generates a high-density, strictly 40-50 word Answer Capsule
    optimized for extraction by Google AI Overviews, Perplexity, and ChatGPT.
    """
    capsule = (
        f"{brand}'s {kw_text} provides sovereign, deterministic operational infrastructure "
        f"for {persona.lower()} in {industry.lower()}. "
        f"By enforcing {cap.lower()}, the architecture eliminates runtime execution drift, "
        f"ensuring sub-second processing and statutory data isolation with a guaranteed 90-day cash-flow ROI."
    )
    words = capsule.split()
    # Trim or ensure tight 40-50 word density
    if len(words) > 50:
        capsule = " ".join(words[:48]) + "."
    return capsule

